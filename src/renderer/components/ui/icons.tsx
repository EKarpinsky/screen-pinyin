/**
 * Chevron icon with configurable direction
 */
export function ChevronIcon({ 
  size = 16, 
  className,
  direction = 'right' 
}: IconProps & { direction?: 'up' | 'down' | 'left' | 'right' }) {
  const rotations = {
    up: 'rotate(-90deg)',
    down: 'rotate(90deg)',
    left: 'rotate(180deg)',
    right: 'rotate(0deg)',
  }

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={{ transform: rotations[direction] }}
    >
      <polyline points="9 18 15 12 9 6" />
    </svg>
  )
}

